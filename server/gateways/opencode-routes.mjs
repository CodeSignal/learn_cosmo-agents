/** Compile a route path to an anchored RegExp. */
export function pathPattern(path) {
  const body = path
    .split("/")
    .map((seg) => (seg === "*" ? ".+" : seg === "{id}" ? "[^/]+" : seg.replace(/[.+?^${}()|[\]\\]/g, "\\$&")))
    .join("/");
  return new RegExp(`^${body}$`);
}
